stat5_1 <- function(mu,sigma,n, a, b){
  p <- pnorm(q=c(a), mean=mu, sd=sigma/sqrt(n)) - pnorm(q=c(b), mean=mu, sd=sigma/sqrt(n))
  print(p)
}

