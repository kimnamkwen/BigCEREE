# 정신지체가 있는 1집단, 정상인 2집단, 두 집단의 지능점수의 분포는 표준편차 20으로
# 거의 정규분포를 함.
# 각각의 집단에서 크기 15명의 표본을 구해서 각각 지능점수의 표본평균을 구하면
# x1=92. x2=105가 된다. 만일 이 두 집단 사이에 차이가 없다면 이 이상의 차이를 갖게 될 확률은?


stat5_2 <- function(n1,n2,sd1,sd2,dif,x1,x2){
  z <- ((x1-x2)-dif)/(sqrt((sd1^2/n1)+(sd2^2/n2)))
  p <- 1- pnorm(q=c(z), mean=0, sd=1)
  print(z)
  print(p)
}

