# 5-5. 이항확률분포의 확률계산

# 어떤 인구집단의 모든 출생기록의 52%가 남자아이 이다.
# 이 인구집단에서 다섯개의 출생기록을 확률적으로 추출하였을 때 그 중 3명이 남자 아이일 확률은?


stat5_5 <- function(n, x, p){
  pr <- (choose(n, x))*(p^x)*((1-p)^(n-x))
  print(pr)
}

stat5_5(5, 3, 0.52)

# 문제 : 1명이 남자 아이일 확률은?

# 답안 :

