stat5_4 <- function(p1, p2, n1, n2, diff){
  d <- p1-p2
  z <- (diff-d)/sqrt((p1*(1-p1)/n1)+(p2*(1-p2)/n2))
  p <- 1-pnorm(q=c(z), mean=0, sd=1)
  print(d)
  print(z)
  print(p)
}

